// Generate a read-only browser projection from the same typed reference imported by /api/meta.
// The compiler is an existing local build dependency; no install, network, API or provider mutation.
"use strict";
const fs = require("node:fs"), path = require("node:path");
const root = path.join(__dirname, ".."), ts = require('node:module').createRequire(path.join(root, 'worker/package.json'))('typescript');
const sourcePath = path.join(root, "worker/src/royal-writs199.ts");
const targetPath = path.join(root, "worker/public/static/royal-writs199.js");
function projection() {
  const source = fs.readFileSync(sourcePath, "utf8");
  const result = ts.transpileModule(source, { fileName: sourcePath, compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, newLine: ts.NewLineKind.LineFeed }, reportDiagnostics: true });
  if (result.diagnostics?.some(d => d.category === ts.DiagnosticCategory.Error)) throw Error("royal_writ_projection_compile");
  const names = ["ROYAL_WRIT_POLICY", "ROYAL_WRIT_CATEGORIES", "ROYAL_WRITS", "STOCKADES_CHECKLIST"];
  const compiled = result.outputText.replace(/^export const (\w+) = /gm, (all, name) => {
    if (!names.includes(name)) throw Error("royal_writ_projection_export");
    return "const " + name + " = ";
  });
  if (/^\s*(?:import|export)\b/m.test(compiled)) throw Error("royal_writ_projection_module");
  return "/* GENERATED by scripts/build-royal-writs199.cjs; edit worker/src/royal-writs199.ts. */\n(function (global) {\n\"use strict\";\n" + compiled + "global.OlympusRoyalWrits199 = Object.freeze({ " + names.join(", ") + " });\n})(globalThis);\n";
}
function run(mode) {
  const expected = projection();
  if (mode === "--write") fs.writeFileSync(targetPath, expected, "utf8");
  else if (fs.readFileSync(targetPath, "utf8") !== expected) throw Error("royal_writ_projection_drift");
  console.log(JSON.stringify({ mode, bytes: Buffer.byteLength(expected), records: 20 }));
}
if (require.main === module) {
  if (process.argv.length !== 3 || !["--check", "--write"].includes(process.argv[2])) throw Error("Use --check or --write");
  run(process.argv[2]);
}
module.exports = { projection };
