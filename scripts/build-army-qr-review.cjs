#!/usr/bin/env node
'use strict';
// Owner scope, 20 Oct 2026: stage reviewed bytes only. Activation and uploads remain unavailable.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const SOURCE = 'tools/guild-qr-pilot', TARGET = 'worker/public/static/army-qr-review';
const PINS = Object.freeze([
  ['protocol.js', 16945, '7bec896812384fb53a0fa2c7754cd2abbb0393e285a857538c3ecdcca3d6be02'],
  ['decoder.js', 1510, 'd700694ed1f78fc9bb359d1a36e3b2395952d73539ba4aad72c2a1ed14b771d3'],
  ['pilot.js', 19956, '096065bd3e7bf5745adbe83a542250d6caea2692b0034926505787fb31293f24'],
  ['pilot.css', 8544, '1f8f4f6e58ef66060eb58934e9955a8b00d36630bea77d4306e25581a7b741d0'],
  ['vendor/jsqr-1.4.0.js', 256885, 'bc40c8a15196236b2314db0856f72ca0b49980cd5413b8c852a7349f5fee0859'],
  ['vendor/jsqr-1.4.0.LICENSE.txt', 11358, 'c6596eb7be8581c18be736c846fb9173b69eccf6ef94c5135893ec56bd92ba08'],
].map(row => Object.freeze(row)));
const PREFIX = Buffer.from("/* Dormant Army QR review bytes. No runtime activation or upload switch. */\n(function () {\n  'use strict';\n  const activation = false, uploads = false;\n  return; // Unconditional source-fixed stop; retained source below is never executed.\n");
const SUFFIX = Buffer.from('\n}());\n');
const DECODER_FROM = "importScripts('./vendor/jsqr-1.4.0.js');", DECODER_TO = "importScripts('../qr-vendor/jsqr-1.4.0.js');";
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
function need(ok, reason) { if (!ok) throw Error(reason); }
function regular(file) { need(fs.lstatSync(file).isFile(), 'Regular package file required: ' + file); return fs.readFileSync(file); }
function prepare(root) {
  const outputs = new Map(), sources = [], reused = [], projections = [];
  for (const [name, bytes, hash] of PINS) {
    const input = regular(path.join(root, SOURCE, name));
    need(input.length === bytes && sha(input) === hash, 'Reviewed Army QR source pin drift: ' + name);
    sources.push({path: SOURCE + '/' + name, bytes, sha256: hash});
    if (name.startsWith('vendor/')) {
      const existing = 'worker/public/static/qr-vendor/' + path.posix.basename(name), deployed = regular(path.join(root, existing));
      need(deployed.equals(input), 'Existing production QR vendor pin drift: ' + name);
      reused.push({path: existing, sourcePath: SOURCE + '/' + name, bytes, sha256: hash});
    } else if (name.endsWith('.js')) {
      let projected = input;
      if (name === 'decoder.js') {
        const text = input.toString('utf8'); need(text.split(DECODER_FROM).length === 2, 'One exact decoder import path projection required');
        projected = Buffer.from(text.replace(DECODER_FROM, DECODER_TO));
        projections.push({path: SOURCE + '/' + name, originalSha256: hash, projectedSha256: sha(projected), projectedBytes: projected.length, from: DECODER_FROM, to: DECODER_TO, substitutions: 1});
      }
      outputs.set(name, Buffer.concat([PREFIX, projected, SUFFIX]));
    }
  }
  const manifest = {
    format: 'olympus-army-qr-dormant-review-v1', activation: false, uploads: false,
    runtimeOverride: false, shippingHtml: false, sourceVerified: false, membershipProof: false,
    sources, reviewOnlySources: [SOURCE + '/pilot.css'], reused, projections,
    generated: [...outputs].map(([name, bytes]) => ({path: TARGET + '/' + name, bytes: bytes.length, sha256: sha(bytes)})),
  };
  outputs.set('manifest.json', Buffer.from(JSON.stringify(manifest, null, 2) + '\n'));
  return outputs;
}
function inventory(dir, prefix = '') {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const name of fs.readdirSync(dir)) {
    const absolute = path.join(dir, name), relative = prefix + name, stat = fs.lstatSync(absolute);
    need(!stat.isSymbolicLink(), 'Package symlink refused: ' + relative);
    if (stat.isDirectory()) out.push(...inventory(absolute, relative + '/'));
    else { need(stat.isFile(), 'Non-file package entry refused: ' + relative); out.push(relative); }
  }
  return out.sort();
}
function build(root, write = false) {
  const outputs = prepare(root), destination = path.join(root, TARGET), existing = inventory(destination);
  need(existing.every(name => outputs.has(name)), 'Unexpected Army QR review package file');
  if (write) {
    for (const [name, bytes] of outputs) { const file = path.join(destination, name); fs.mkdirSync(path.dirname(file), {recursive: true}); fs.writeFileSync(file, bytes); }
  }
  need(JSON.stringify(inventory(destination)) === JSON.stringify([...outputs.keys()].sort()), 'Army QR review package inventory drift');
  for (const [name, expected] of outputs) need(regular(path.join(destination, name)).equals(expected), 'Army QR review generated byte drift: ' + name);
  return {files: outputs.size, activation: false, uploads: false};
}
if (require.main === module) {
  try {
    const args = process.argv.slice(2); need(args.length <= 1 && (!args.length || ['--check', '--write'].includes(args[0])), 'Use --check (default) or --write');
    const result = build(path.resolve(__dirname, '..'), args[0] === '--write');
    console.log('PASS dormant Army QR review package: ' + result.files + ' exact files; activation=false; uploads=false');
  } catch (error) { console.error('FAIL ' + error.message); process.exitCode = 1; }
}
module.exports = Object.freeze({build, prepare, SOURCE, TARGET, PINS, PREFIX, SUFFIX, DECODER_FROM, DECODER_TO});
