// Exact source projection for application attachments. Local files only; no provider, SQL or runtime lane.
'use strict';
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto'), vm = require('node:vm');
const root = path.join(__dirname, '..');
const INPUT_SHA256 = '8b174d764836675b2b759050f441e2dfe12c7bad6a5b279ef39b05d8b1288a0c';
const UPSTREAM_SHA256 = '260cf99b52db5fd0085043d4d3c2d5dde1b47dffe88b9696c94caccc9fb03588';
const CALCULATOR_SHA256 = '0830ff6fc69ef3a3430bf1cdf31a272f3a5a84da4bcedfba2ae398748cd131c8';
const REVISION = '260cf99b52db';
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
function projectSnapshot(data, calculator) {
  const validation = calculator.validateData(data);
  if (!validation.ok || data.revision !== REVISION || data.source.rawSHA256 !== UPSTREAM_SHA256) throw Error('talent_snapshot_contract');
  const classes = {};
  for (const cls of data.classes) {
    const flattened = cls.trees.flatMap(tree => tree.talents);
    const indices = new Map(flattened.map((talent, index) => [talent.id, index]));
    classes[cls.id] = cls.trees.flatMap((tree, treeIndex) => tree.talents.map(talent => {
      const prerequisite = talent.requires ? indices.get(talent.requires) : -1;
      if (prerequisite === undefined) throw Error('talent_prerequisite_missing');
      return [talent.maxRank, talent.row, treeIndex, prerequisite];
    }));
  }
  return classes;
}
function renderContract(classes) {
  return `/** Generated by scripts/build-talent-build-contract.cjs from the pinned actual calculator snapshot.
 * Tuple order: maximum rank, one-based talent row, zero-based tree, flattened prerequisite index (-1 when absent).
 * Public talent constraints only. No user, URL, remote response or character stat is stored here. */
export const TALENT_SNAPSHOT_REVISION = "${REVISION}";
export const TALENT_SNAPSHOT_DATA_SHA256 = "${INPUT_SHA256}";
export const TALENT_SNAPSHOT_UPSTREAM_SHA256 = "${UPSTREAM_SHA256}";
export const TALENT_SERIALIZER_SOURCE_SHA256 = "${CALCULATOR_SHA256}";
export const TALENT_ATTACHMENT_CLASSES:Readonly<Record<string,readonly (readonly number[])[]>> = Object.freeze(Object.fromEntries(Object.entries(${JSON.stringify(classes)}).map(([key, rows]) => [key,Object.freeze(rows.map(row => Object.freeze(row)))])));
`;
}
function buildContract(repo = root) {
  const folder = path.join(repo, 'worker/public/static/talents');
  const raw = fs.readFileSync(path.join(folder, 'data.json')), source = fs.readFileSync(path.join(folder, 'calculator.js'));
  const provenance = JSON.parse(fs.readFileSync(path.join(folder, 'provenance.json'), 'utf8'));
  if (hash(raw) !== INPUT_SHA256 || provenance.normalizedSHA256 !== INPUT_SHA256 || provenance.normalizedBytes !== raw.length || hash(source) !== CALCULATOR_SHA256) throw Error('talent_input_hash_changed');
  const commonJS = { exports: {} };
  vm.runInNewContext(source.toString('utf8'), { module: commonJS }, { filename: 'calculator.js', timeout: 1000 });
  return renderContract(projectSnapshot(JSON.parse(raw), commonJS.exports));
}
function main(args) {
  if (args.length > 1 || args.length === 1 && args[0] !== '--check') throw Error('unsupported_argument');
  const source = buildContract(), target = path.join(root, 'worker/src/talent-build-contract.ts');
  if (args[0] === '--check') {
    if (fs.readFileSync(target, 'utf8') !== source) throw Error('talent_attachment_projection_drift');
  } else fs.writeFileSync(target, source);
}
module.exports = { buildContract, projectSnapshot, renderContract, INPUT_SHA256, UPSTREAM_SHA256, CALCULATOR_SHA256, REVISION };
if (require.main === module) main(process.argv.slice(2));
