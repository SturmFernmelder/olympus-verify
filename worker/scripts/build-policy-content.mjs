#!/usr/bin/env node
// Build .65 (1 Oct 2026): generates worker/src/policy-content.ts from the tracked policies/privacy.html and
// policies/terms.html, so the Worker's canonical /privacy and /terms (Codex's countersigned delivery candidate,
// manifest 5519466c…, 02:31 UTC) can never drift from the tracked text the GitHub Pages mirror publishes. The main
// text is copied unchanged; only the page shell differs: the inline <style> gives way to /static/policies.css, a skip
// link, a header with the two policies' navigation, and site-relative "See also" links.
//   node scripts/build-policy-content.mjs            writes src/policy-content.ts
//   node scripts/build-policy-content.mjs --check    exits 1 when the committed file is not what the sources give
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..", "..");
const out = path.join(repo, "worker", "src", "policy-content.ts");
const PAGES = [
  { file: "privacy.html", self: "/privacy", heading: "Privacy Policy" },
  { file: "terms.html", self: "/terms", heading: "Terms of Service" },
];

function shell(source, page) {
  const title = /<title>([^<]*)<\/title>/.exec(source)?.[1];
  const main = /<main>\n([\s\S]*?)\n<\/main>/.exec(source)?.[1];
  if (!title || !main) throw new Error(`${page.file}: no <title> or <main>`);
  // the only markup that changes inside <main>: the closing "See also" line's inline style and its Pages-relative link
  const body = main
    .replace('<p class="meta" style="margin-top:2.5rem">See also the <a href="./terms.html">', '<p class="meta related">See also the <a href="/terms">')
    .replace('<p class="meta" style="margin-top:2.5rem">See also the <a href="./privacy.html">', '<p class="meta related">See also the <a href="/privacy">');
  if (/style=|\.\/(privacy|terms)\.html/.test(body)) throw new Error(`${page.file}: an inline style or a Pages-relative link survived`);
  const nav = PAGES.map((p) => `<a href="${p.self}"${p === page ? ' aria-current="page"' : ""}>${p.heading}</a>`).join("");
  return [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width,initial-scale=1">',
    `<title>${title}</title>`,
    '<meta name="color-scheme" content="dark">',
    '<link rel="stylesheet" href="/static/policies.css">',
    "</head>",
    '<body class="olympus-policy">',
    '<a class="skip-link" href="#policy-content">Skip to policy</a>',
    '<header class="policy-header">',
    '<a class="brand" href="/">Olympus</a>',
    `<nav aria-label="Policies">${nav}</nav>`,
    "</header>",
    '<main id="policy-content" tabindex="-1">',
    body,
    "</main>",
    "</body>",
    "</html>",
    "",
  ].join("\n");
}

const docs = PAGES.map((page) => ({ page, html: shell(fs.readFileSync(path.join(repo, "policies", page.file), "utf8"), page) }));
// .114: the Battle.net sign-in switch (src/bnet-switch.ts) can be turned on only while the privacy policy describes the
// login; a policy section that does carries this marker comment, and nothing else sets the constant.
const BNET_MARKER = "<!-- olympus:bnet-login-section -->";
const generated = [
  "// GENERATED by worker/scripts/build-policy-content.mjs from policies/privacy.html and policies/terms.html; do not edit.",
  "// The main text is the tracked policy text unchanged; the shell is the Worker's (.65). `npm run check:policies` fails when stale.",
  `const PRIVACY = ${JSON.stringify(docs[0].html)};`,
  `const TERMS = ${JSON.stringify(docs[1].html)};`,
  "",
  `/** .114: whether the privacy policy carries the marked Battle.net sign-in section (${BNET_MARKER}); gates src/bnet-switch.ts. */`,
  `export const PRIVACY_DESCRIBES_BNET_LOGIN = ${docs[0].html.includes(BNET_MARKER)};`,
  "",
  "/** The canonical policy document a path names, or null. Aliases keep every address that ever served or redirected one. */",
  "export function policyDocument(path: string): string | null {",
  '  if (["/privacy", "/privacy-policy", "/privacy.html"].includes(path)) return PRIVACY;',
  '  if (["/terms", "/tos", "/terms-of-service", "/terms.html"].includes(path)) return TERMS;',
  "  return null;",
  "}",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== generated) {
    console.error("policy-content: src/policy-content.ts is not what policies/*.html give; run: node scripts/build-policy-content.mjs");
    process.exit(1);
  }
  console.log("policy-content: src/policy-content.ts matches policies/privacy.html and policies/terms.html");
} else {
  fs.writeFileSync(out, generated);
  console.log(`policy-content: wrote ${path.relative(repo, out)}`);
}
