"""Generate only the pure, versioned native rank constants in three runtimes."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'contracts/native-rank-schemes.json').read_text(encoding='utf-8'))
assert data['version'] == 1 and len(data['names']) == len(set(data['names'])) == 10
assert len(data['canonicalIndexes']) == 10
serial = 'olympus-native-ranks|1|10|' + '|'.join(f'{i}:{len(n.encode())}:{n}' for i, n in enumerate(data['names']))
digest = hashlib.sha256(serial.encode()).hexdigest()
ts = '// Generated by tools/build-native-ranks.py; historical profiles are deliberately not rewritten.\n'
ts += f'export const DIRECTIVE_NATIVE_PROFILE = {json.dumps(data["nativeProfile"])} as const;\n'
ts += f'export const DIRECTIVE_CANONICAL_PROFILE = {json.dumps(data["canonicalProfile"])} as const;\n'
ts += f'export const DIRECTIVE_RANK_NAMES = Object.freeze({json.dumps(data["names"])} as const);\n'
ts += f'export const DIRECTIVE_CANONICAL_INDEX = Object.freeze({json.dumps(data["canonicalIndexes"])} as const);\n'
ts += f'export const DIRECTIVE_RANK_DIGEST = "{digest}" as const;\n'
ts += 'export const DIRECTIVE_TARGETS = Object.freeze(' + json.dumps({k:data[k] for k in ['veteran','member','alt','initiate']}) + ');\n'
py = '# Generated by tools/build-native-ranks.py; historical profiles stay separate.\n'
py += f'NATIVE_PROFILE = {data["nativeProfile"]!r}\nCANONICAL_PROFILE = {data["canonicalProfile"]!r}\n'
py += f'NAMES = {tuple(data["names"])!r}\nCANONICAL_INDEXES = {tuple(data["canonicalIndexes"])!r}\nSCHEME_DIGEST = {digest!r}\n'
py += '\n'.join(k.upper()+' = '+str(data[k]) for k in ['veteran','member','alt','initiate'])+'\n'
lua = '-- Generated by tools/build-native-ranks.py. This table is expectation, never observation.\n'
lua += 'OlympusVerifyNativeRankConstants = { version=1, profile='+json.dumps(data['nativeProfile'])+', digest='+json.dumps(digest)+', names={' + ','.join(json.dumps(n) for n in data['names']) + '}, veteran=5, member=7, alt=8, initiate=9 }\n'
for target, content in [('worker/src/native-rank-constants.ts',ts),('watcher/native_rank_schemes.py',py),('addon/OlympusVerify/OlympusVerifyNativeRankConstants.lua',lua)]:
    (ROOT/target).write_text(content,encoding='utf-8',newline='\n')
