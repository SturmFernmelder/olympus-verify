"""Generate only the pure, versioned native rank constants in three runtimes."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'contracts/native-rank-schemes.json').read_text(encoding='utf-8'))
assert data['version'] == 1
profiles = [data, *data.get('profiles', [])]
assert len(profiles) == 2
targets = ['veteran', 'member', 'alt', 'initiate']
for profile in profiles:
    assert len(profile['names']) == len(set(profile['names'])) == 10
    assert len(profile['canonicalIndexes']) == 10
    assert all(type(profile[k]) is int and 0 <= profile[k] < 10 for k in targets)
    assert all(profile['names'][profile[k]] == k.title() for k in targets)
    serial = 'olympus-native-ranks|1|10|' + '|'.join(f'{i}:{len(n.encode())}:{n}' for i, n in enumerate(profile['names']))
    profile['digest'] = hashlib.sha256(serial.encode()).hexdigest()
assert len({p['nativeProfile'] for p in profiles}) == len(profiles)
digest = data['digest']
ts = '// Generated by tools/build-native-ranks.py; historical profiles are deliberately not rewritten.\n'
ts += f'export const DIRECTIVE_NATIVE_PROFILE = {json.dumps(data["nativeProfile"])} as const;\n'
ts += f'export const DIRECTIVE_CANONICAL_PROFILE = {json.dumps(data["canonicalProfile"])} as const;\n'
ts += f'export const DIRECTIVE_RANK_NAMES = Object.freeze({json.dumps(data["names"])} as const);\n'
ts += f'export const DIRECTIVE_CANONICAL_INDEX = Object.freeze({json.dumps(data["canonicalIndexes"])} as const);\n'
ts += f'export const DIRECTIVE_RANK_DIGEST = "{digest}" as const;\n'
ts += 'export const DIRECTIVE_TARGETS = Object.freeze(' + json.dumps({k:data[k] for k in ['veteran','member','alt','initiate']}) + ');\n'
py = '# Generated by tools/build-native-ranks.py; historical profiles stay separate.\n'
py += f'NATIVE_PROFILE = {data["nativeProfile"]!r}\nCANONICAL_PROFILE = {data["canonicalProfile"]!r}\n'
py += f'NAMES = {tuple(data["names"])!r}\nCANONICAL_INDEXES = {tuple(data["canonicalIndexes"])!r}\nSCHEME_DIGEST = {digest!r}\n'
py += '\n'.join(k.upper()+' = '+str(data[k]) for k in ['veteran','member','alt','initiate'])+'\n'
lua = '-- Generated by tools/build-native-ranks.py. This table is expectation, never observation.\n'
lua += 'OlympusVerifyNativeRankConstants = { version=1, profile='+json.dumps(data['nativeProfile'])+', digest='+json.dumps(digest)+', names={' + ','.join(json.dumps(n) for n in data['names']) + '}, ' + ', '.join(k+'='+str(data[k]) for k in targets) + ' }\n'
for prefix, p in [('STEWARD', profiles[1])]:
    ts += f'export const {prefix}_NATIVE_PROFILE = {json.dumps(p["nativeProfile"])} as const;\n'
    ts += f'export const {prefix}_CANONICAL_PROFILE = {json.dumps(p["canonicalProfile"])} as const;\n'
    ts += f'export const {prefix}_RANK_NAMES = Object.freeze({json.dumps(p["names"])} as const);\n'
    ts += f'export const {prefix}_CANONICAL_INDEX = Object.freeze({json.dumps(p["canonicalIndexes"])} as const);\n'
    ts += f'export const {prefix}_RANK_DIGEST = {json.dumps(p["digest"])} as const;\n'
    ts += f'export const {prefix}_TARGETS = Object.freeze(' + json.dumps({k:p[k] for k in targets}) + ');\n'
ts += 'export const NATIVE_RANK_SCHEMES = Object.freeze([\n'
for prefix in ['DIRECTIVE', 'STEWARD']:
    ts += f' Object.freeze({{profile:{prefix}_NATIVE_PROFILE,canonicalProfile:{prefix}_CANONICAL_PROFILE,names:{prefix}_RANK_NAMES,canonicalIndexes:{prefix}_CANONICAL_INDEX,digest:{prefix}_RANK_DIGEST,...{prefix}_TARGETS}}),\n'
ts += '] as const);\nexport type NativeRankScheme = typeof NATIVE_RANK_SCHEMES[number];\n'
py += 'PROFILES = (\n'
for p in profiles:
    py += '    ' + repr(dict(profile=p['nativeProfile'], canonical_profile=p['canonicalProfile'], names=tuple(p['names']), canonical_indexes=tuple(p['canonicalIndexes']), digest=p['digest'], **{k:p[k] for k in targets})) + ',\n'
py += ')\ndef rank_scheme(profile, digest):\n    return next((p for p in PROFILES if p["profile"] == profile and p["digest"] == digest), None)\n'
p = profiles[1]
original_lua = lua.split(' = ', 1)[1].strip()
lua += 'OlympusVerifyNativeRankConstants.profiles = {'+original_lua+',{version=1,profile='+json.dumps(p['nativeProfile'])+',digest='+json.dumps(p['digest'])+',names={' + ','.join(json.dumps(n) for n in p['names']) + '},' + ','.join(k+'='+str(p[k]) for k in targets) + '}}\n'
for target, content in [('worker/src/native-rank-constants.ts',ts),('watcher/native_rank_schemes.py',py),('addon/OlympusVerify/OlympusVerifyNativeRankConstants.lua',lua)]:
    (ROOT/target).write_text(content,encoding='utf-8',newline='\n')
